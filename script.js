    function renderProducts(categoryFilter = "all") {
      const grid = document.getElementById("productsGrid");
      const filtered = categoryFilter === "all"
        ? products
        : products.filter((p) => p.category === categoryFilter);

      grid.innerHTML = filtered.map((product) => `
        <div class="col-12 col-sm-6 col-lg-4">
          <div class="product-card">
            <div class="product-img-wrap">
              <span class="product-badge">${product.tag}</span>
              <img src="${product.imgPrimary}"
                   onerror="this.src='https://placehold.co/600x800/ece7df/181716?text=SHRI.+SV+TRAILER'"
                   class="primary-img" alt="${product.title}" />
              <img src="${product.imgSecondary}"
                   onerror="this.src='https://placehold.co/600x800/ece7df/181716?text=COUTURE+DETAIL'"
                   class="secondary-img" alt="${product.title} Detail" />
              <div class="product-actions-overlay">
                <button type="button" class="btn-quick-view" onclick="openQuickView(${product.id})">View Couture Dossier</button>
                <button type="button" class="btn-add-bag" onclick="inquireCouturePiece('${product.title.replace(/'/g, "\\'")}')">Inquire Bespoke</button>
              </div>
            </div>
            <div class="product-meta">
              <div class="product-designer">SHRI. SV TRAILER</div>
              <h3 class="product-title" onclick="openQuickView(${product.id})">${product.title}</h3>
              <div class="product-price">${formatINR(product.price)}</div>
            </div>
          </div>
        </div>
      `).join("");
    }

    function filterProducts(category) {
      document.querySelectorAll("#productFilterTabs .nav-link").forEach((btn) => {
        btn.classList.toggle("active", btn.dataset.filter === category);
      });
      renderProducts(category);
    }

    function scrollToCollection(category) {
      filterProducts(category);
      document.getElementById("collections-section").scrollIntoView({ behavior: "smooth" });
    }

    function inquireCouturePiece(title) {
      const notesField = document.getElementById("bespokeNotes");
      if (notesField) {
        notesField.value = `I would like to schedule a private consultation regarding: ${title}.`;
      }
      document.getElementById("contact-section").scrollIntoView({ behavior: "smooth" });
      showToast(`Selected "${title}" for your private consultation inquiry.`);
    }

    /* ========================================================================
       FULL-SCREEN LEGAL & AUTHENTICITY PAGE VIEWER LOGIC
       ======================================================================== */
    function openLegalPage(pageKey) {
      const doc = legalDocuments[pageKey];
      if (!doc) return;

      document.getElementById("legalDocEyebrow").textContent = doc.eyebrow;
      document.getElementById("legalDocTitle").textContent = doc.title;
      document.getElementById("legalDocContent").innerHTML = doc.content;

      ["privacy", "terms", "authenticity"].forEach((key) => {
        const btn = document.getElementById(`tab-${key}`);
        if (btn) btn.classList.toggle("active", key === pageKey);
      });

      const overlay = document.getElementById("legalPageOverlay");
      overlay.classList.add("active");
      overlay.scrollTop = 0;
      document.body.style.overflow = "hidden";
    }

    function closeLegalPage() {
      const overlay = document.getElementById("legalPageOverlay");
      overlay.classList.remove("active");
      document.body.style.overflow = "";
    }

    // Close legal view on Escape key
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape") {
        closeLegalPage();
      }
    });

